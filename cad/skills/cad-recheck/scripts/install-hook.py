#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Install the CAD recheck pre-commit hook in a hardware project.

The hook lives in <repository>/.githooks/, which becomes the repository-local core.hooksPath.
The hooks the repository ran before keep running: a core.hooksPath set at any scope (such as an
organisation's global hooks directory) or the hooks in .git/hooks/. The installer records that
directory as the repository-local `cad-recheck.chainedHooksPath`; the CAD pre-commit runs its
pre-commit first, and each other hook it holds gets a .githooks/ shim that runs it. Only the
repository's own config and .githooks/ are written; the chained directory and every other config
scope stay unchanged. --force replaces the previous hooks instead of chaining them.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

CHAIN_KEY = "cad-recheck.chainedHooksPath"
# The hooks git looks up in core.hooksPath (githooks(5)); pre-commit is the CAD hook itself.
GIT_HOOKS = (
    "applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit", "pre-merge-commit",
    "prepare-commit-msg", "commit-msg", "post-commit", "pre-rebase", "post-checkout", "post-merge",
    "pre-push", "pre-receive", "update", "proc-receive", "post-receive", "post-update",
    "reference-transaction", "push-to-checkout", "pre-auto-gc", "post-rewrite", "sendemail-validate",
    "fsmonitor-watchman", "p4-changelist", "p4-prepare-changelist", "p4-post-changelist", "p4-pre-submit",
    "post-index-change",
)
SHIM = (
    "#!/bin/sh\n"
    "# Generated by cad-recheck install-hook.py: run the chained hook of the same name.\n"
    'exec "$(dirname -- "$0")/cad-recheck-chain" "$(basename -- "$0")" "$@"\n'
)


def git(*args: str, cwd: Path) -> str:
    result = subprocess.run(
        ["git", *args], cwd=cwd, text=True, capture_output=True, check=False
    )
    if result.returncode:
        detail = result.stderr.strip() or f"git {' '.join(args)} failed ({result.returncode})"
        raise RuntimeError(detail)
    return result.stdout.rstrip("\n")


def hooks_directory(root: Path) -> Path:
    """The directory git runs hooks from: core.hooksPath at its effective scope, else .git/hooks."""
    path = Path(git("rev-parse", "--git-path", "hooks", cwd=root))
    return (path if path.is_absolute() else root / path).resolve()


def recorded_chain(root: Path) -> Path | None:
    result = subprocess.run(
        ["git", "config", "--local", "--get", CHAIN_KEY], cwd=root, text=True, capture_output=True, check=False
    )
    if result.returncode == 1:
        return None
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or f"cannot read {CHAIN_KEY}")
    return Path(result.stdout.strip())


def chainable_hooks(directory: Path) -> list[str]:
    """The git hooks `directory` holds as executable files."""
    return [name for name in GIT_HOOKS
            if (directory / name).is_file() and os.access(directory / name, os.X_OK)]


def install(project: Path, scripts: Path, *, force: bool = False) -> tuple[Path, Path | None]:
    """Install .githooks/ and return its pre-commit and the chained hooks directory, if any."""
    root = Path(git("rev-parse", "--show-toplevel", cwd=project)).resolve()
    hooks_dir = root / ".githooks"
    previous = hooks_directory(root)
    if force:
        chained = None
    elif previous == hooks_dir.resolve():
        chained = recorded_chain(root)
    else:
        chained = previous if chainable_hooks(previous) else None
    shims = [name for name in chainable_hooks(chained) if name != "pre-commit"] if chained else []

    source = scripts / "pre-commit"
    hook = hooks_dir / "pre-commit"
    planned = {hook: source.read_bytes(), **{hooks_dir / name: SHIM.encode() for name in shims}}
    stamp = hooks_dir / "cad-recheck-stamp.py"
    chain = hooks_dir / "cad-recheck-chain"
    for target in (*planned, stamp, chain):
        if target.exists() and not target.is_file():
            raise RuntimeError(f"cannot replace non-file path: {target}")
    for target, content in planned.items():
        if not force and target.exists() and target.read_bytes() != content:
            raise RuntimeError(f"refusing to overwrite existing hook with different contents: {target}")

    hooks_dir.mkdir(parents=True, exist_ok=True)
    for target, content in planned.items():
        target.write_bytes(content)
    shutil.copyfile(scripts / "stamp.py", stamp)
    shutil.copyfile(scripts / "chain-hook", chain)
    record_root = scripts.parents[1] / "cad-record"
    motion_scripts = scripts.parents[1] / "cad-motion" / "scripts"
    hook_motion = hooks_dir / "cad-motion" / "scripts"
    hook_motion.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(motion_scripts / "coupling.py", hook_motion / "coupling.py")
    hook_layout = hooks_dir / "cad-record"
    (hook_layout / "scripts").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(record_root / "scripts" / "layout.py", hook_layout / "scripts" / "layout.py")
    shutil.copyfile(record_root / "layout.json", hook_layout / "layout.json")
    shutil.copytree(record_root / "schemas", hook_layout / "schemas", dirs_exist_ok=True)
    shutil.copyfile(record_root / "scripts" / "validate.py", hook_layout / "scripts" / "validate.py")
    shutil.copyfile(record_root / "scripts" / "assembly_data.py", hook_layout / "scripts" / "assembly_data.py")
    for target in (*planned, stamp, chain):
        target.chmod(target.stat().st_mode | 0o111)

    if chained is not None:
        git("config", "--local", CHAIN_KEY, str(chained), cwd=root)
    elif recorded_chain(root) is not None:
        git("config", "--local", "--unset-all", CHAIN_KEY, cwd=root)
    git("config", "--local", "core.hooksPath", ".githooks", cwd=root)
    if hooks_directory(root) != hooks_dir.resolve():
        raise RuntimeError(
            f"set core.hooksPath=.githooks in {root}/.git/config, but git still runs hooks from "
            f"{hooks_directory(root)}: a worktree-scope core.hooksPath overrides it"
        )
    return hook, chained


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", type=Path, default=Path.cwd(), help="hardware project git repository")
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace the hooks git ran before instead of chaining them, and overwrite differing .githooks/ hooks",
    )
    args = parser.parse_args()
    scripts = Path(__file__).resolve().parent
    try:
        hook, chained = install(args.project.resolve(), scripts, force=args.force)
    except (OSError, RuntimeError) as error:
        print(f"cad-recheck install-hook: {error}", file=sys.stderr)
        return 2
    print(f"Installed {hook} and configured the repository-local core.hooksPath=.githooks")
    if chained is not None:
        print(f"The hooks in {chained} still run first: recorded as the repository-local {CHAIN_KEY}.")
    print("Commit .githooks/ so the hook and its stamp tool are available in other checkouts.")
    if args.force:
        print("--force replaced the hooks configured previously; they no longer run.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
