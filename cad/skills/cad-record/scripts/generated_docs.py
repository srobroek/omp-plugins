"""The marker on each document build_guide.py generates, and the release fields release.py reads back.

The first line of a generated document names build_guide.py and the sha256 of every line after it.
build_guide.py overwrites a document only while that marker still matches: a file without it is
someone's own, and a file whose lines changed after generation was edited by hand. release.py checks
that a generated okh.toml describes the release that copies it.
"""

from __future__ import annotations

import hashlib
import re
import tomllib
from pathlib import Path
from typing import Any

MARKER = re.compile(r"(?:# |<!-- )Generated by cad-record build_guide\.py; sha256 ([0-9a-f]{64}) ")


def _digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def stamp(name: str, body: str) -> str:
    """`body` with the marker line on top, as a TOML comment for a .toml file, else an HTML comment."""
    note = (f"Generated by cad-record build_guide.py; sha256 {_digest(body)} of the lines below. "
            "Change the record and regenerate; a hand edit makes this file yours, and build_guide.py then "
            "overwrites it only with --replace.")
    return (f"# {note}\n" if name.endswith(".toml") else f"<!-- {note} -->\n") + body


def state(path: Path) -> str | None:
    """None when `path` does not exist; `generated` while its marker matches the lines below it; `edited`
    when they changed since; `foreign` without a marker (or when it is not UTF-8 text)."""
    if not path.exists() and not path.is_symlink():
        return None
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return "foreign"
    first, _, body = text.partition("\n")
    match = MARKER.match(first)
    if match is None:
        return "foreign"
    return "generated" if match.group(1) == _digest(body) else "edited"


def okh_release(path: Path) -> dict[str, Any] | None:
    """The `version`, `release` and `release_date` of a build_guide.py okh.toml, edited or not; None when
    there is no such file or it was written by hand. ValueError when it is not valid TOML."""
    if state(path) not in ("generated", "edited"):
        return None
    try:
        document = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as error:
        raise ValueError(f"not valid TOML: {error}") from error
    fields = document.get("okhv") if isinstance(document.get("okhv"), dict) else {}
    return {key: fields.get(key) for key in ("version", "release", "release_date")}
